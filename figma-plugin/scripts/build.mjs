#!/usr/bin/env node
/*
 * Bundles the captured app data into ui.html (Figma plugins load exactly one
 * UI file, so CSS, JS, screens, images and SVGs are all inlined).
 *   node figma-plugin/scripts/build.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'data');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

// Page titles in the Figma file, in order. Scenario pages map onto these.
const PAGES = [
  { title: 'Cover', note: 'title, stats, page index' },
  { title: 'Foundations', note: 'colour variables, type, radius, spacing, elevation' },
  { title: 'Components', note: 'icons, status bar, tab bar' },
  { title: '01 Onboarding', from: 'Onboarding' },
  { title: '02 Home', from: 'Home' },
  { title: '03 Learn', from: 'Learn', note: 'news, videos, articles' },
  { title: '04 Events', from: 'Events' },
  { title: '05 Orders & bookings', from: 'Orders & bookings' },
  { title: '06 My forms', from: 'Forms' },
  { title: '07 Fields', from: 'Fields' },
  { title: '08 Notifications', from: 'Notifications' },
  { title: '09 Account', from: 'Account' },
  { title: '10 States · Empty', from: 'States · Empty' },
  { title: '11 States · Loading', from: 'States · Loading' },
  { title: '12 States · Error & offline', from: 'States · Error & offline' },
  { title: '13 States · Success', from: 'States · Success' },
  { title: '14 States · Permission', from: 'States · Permission' },
  { title: '15 Dark mode', from: 'Dark mode' },
  { title: '16 Design system', from: 'Design system' },
];
const pageTitle = Object.fromEntries(PAGES.filter((p) => p.from).map((p) => [p.from, p.title]));

const index = JSON.parse(fs.readFileSync(path.join(DATA, 'screens.json'), 'utf8'));
const assetIndex = JSON.parse(fs.readFileSync(path.join(DATA, 'assets.json'), 'utf8'));
const tokens = JSON.parse(fs.readFileSync(path.join(DATA, 'tokens.json'), 'utf8'));

const problems = [];
const screens = [];
const used = new Set();
for (const rec of index) {
  const file = path.join(DATA, 'screens', rec.id + '.json');
  if (!fs.existsSync(file)) {
    problems.push('missing screen file ' + rec.id);
    continue;
  }
  const { root } = JSON.parse(fs.readFileSync(file, 'utf8'));
  const title = pageTitle[rec.page];
  if (!title) problems.push('no page for ' + rec.page);
  (function walk(n) {
    (n.fills || []).forEach((f) => f.k === 'I' && used.add(f.ref));
    if (n.t === 'V') {
      used.add(n.ref);
      if (n.png) used.add(n.png);
    }
    (n.c || []).forEach(walk);
  })(root);
  screens.push({ page: title, name: rec.name, rec: { ...rec, page: title }, root });
}

const assets = {};
for (const id of used) {
  const a = assetIndex[id];
  if (!a) {
    problems.push('missing asset ' + id);
    continue;
  }
  const buf = fs.readFileSync(path.join(DATA, 'assets', a.file));
  assets[id] = a.kind === 'svg' ? { kind: 'svg', text: buf.toString('utf8') } : { kind: a.kind, b64: buf.toString('base64') };
}

// The client logo (the splash screen image) for the UI header and the cover.
let logo = null;
const splash = screens.find((s) => s.rec.id === 'splash');
if (splash) {
  (function walk(n) {
    if (logo) return;
    const img = (n.fills || []).find((f) => f.k === 'I');
    if (img && /logo|Kisani/i.test(n.n)) logo = { id: img.ref, ratio: n.w / n.h };
    (n.c || []).forEach(walk);
  })(splash.root);
}
let logoSrc = '';
if (logo && assets[logo.id]) {
  const png = Buffer.from(assets[logo.id].b64, 'base64');
  if (png.slice(1, 4).toString() === 'PNG') logo.ratio = png.readUInt32BE(16) / png.readUInt32BE(20);
  logoSrc = 'data:image/png;base64,' + assets[logo.id].b64;
}

const pagesWithData = PAGES.filter((p) => !p.from || screens.some((s) => s.page === p.title));
const bundle = { version: 1, generated: new Date().toISOString(), pages: pagesWithData.map(({ title, note }) => ({ title, note })), screens, assets, tokens, logo };
const json = JSON.stringify(bundle).replace(/<\//g, '<\\/').replace(/<!--/g, '<\\!--');

let html = read('src/ui.template.html')
  .replace('/*__UI_CSS__*/', () => read('src/ui.css'))
  .replace('/*__UI_JS__*/', () => read('src/ui.js'))
  .replace('/*__LOGO_SRC__*/', () => logoSrc)
  .replace('/*__DATA__*/', () => json);
fs.writeFileSync(path.join(ROOT, 'ui.html'), html);

// Human-readable inventory of everything the plugin builds.
const lines = ['# Kisani Urjaa · Figma import inventory', '', `Generated by \`scripts/build.mjs\` from the capture on ${bundle.generated.slice(0, 10)}. ${screens.length} frames across ${pagesWithData.length} Figma pages.`, ''];
// Coverage of the UI states the brief asked for.
const COVERAGE = [
  ['No bookings available', ['empty-bookings']],
  ['No orders placed', ['empty-orders']],
  ['No search results found', ['empty-search']],
  ['No notifications', ['empty-notifications', 'empty-notifications-read']],
  ['No saved items or records', ['empty-bookmarks', 'empty-step', 'empty-crops', 'empty-forms']],
  ['No data available', ['empty-learn', 'empty-events', 'empty-lands', 'empty-home', 'empty-booking-fields']],
  ['Loading states and skeleton screens', index.filter((r) => r.id.startsWith('loading-')).map((r) => r.id)],
  ['Error states and failed requests', ['error-order', 'error-content', 'error-land', 'error-404', 'offline-order-fail', 'auth-error-short', 'auth-error-prefix', 'otp-error', 'new-order-error', 'booking-step1-error', 'new-land-error', 'password-error']],
  ['No internet connection', index.filter((r) => r.id.startsWith('offline-')).map((r) => r.id).concat(['dark-offline'])],
  ['Success and confirmation states', ['order-placed', 'booking-requested', 'toast-saved', 'toast-interest', 'toast-profile', 'notifications-read', 'verify-done']],
  ['Disabled and active states', ['otp', 'notifications-read', 'orders-filter', 'learn-category', 'booking-step1-filled', 'booking-step2', 'events-day', 'display', 'design-system']],
  ['Permission-related states', ['location', 'location-denied', 'gate-sheet', 'gate-orders', 'gate-otp', 'home-unverified', 'account-unverified', 'verify', 'auth-skip-sheet']],
];
const byId = Object.fromEntries(screens.map((s) => [s.rec.id, s]));
lines.push('## State coverage', '', '| State | Frames |', '|---|---|');
for (const [label, ids] of COVERAGE) {
  const names = ids.filter((id) => byId[id]).map((id) => `${byId[id].name} *(${byId[id].page})*`);
  const missing = ids.filter((id) => !byId[id]);
  if (missing.length) problems.push('coverage refers to missing frames: ' + missing.join(', '));
  lines.push(`| ${label} | ${names.join('<br>')} |`);
}
lines.push('', 'Buttons also exist as components with **State = Default / Disabled / Loading**, chips with **Selected = On / Off**, and the tab bar with **Active = Home / Learn / Orders / Account**.', '');
lines.push('## Pages', '');
lines.push('| Figma page | Frames |', '|---|---|');
for (const p of pagesWithData) lines.push(`| ${p.title} | ${p.from ? screens.filter((s) => s.page === p.title).length : '—  ' + (p.note || '')} |`);
lines.push('');
for (const p of pagesWithData.filter((x) => x.from)) {
  lines.push(`## ${p.title}`, '');
  let group = null;
  for (const s of screens.filter((x) => x.page === p.title)) {
    if (s.rec.group !== group) {
      group = s.rec.group;
      lines.push('', `**${group}**`, '', '| Frame | Route | Size |', '|---|---|---|');
    }
    lines.push(`| ${s.name}${s.rec.desc ? ' — ' + s.rec.desc : ''} | \`${s.rec.at || s.rec.route}\` | ${Math.round(s.rec.w)}×${Math.round(s.rec.h)} |`);
  }
  lines.push('');
}
fs.writeFileSync(path.join(ROOT, 'INVENTORY.md'), lines.join('\n'));

const mb = (fs.statSync(path.join(ROOT, 'ui.html')).size / 1e6).toFixed(1);
console.log(`ui.html: ${screens.length} screens, ${Object.keys(assets).length} assets, ${mb} MB, logo ${logo ? 'yes' : 'no'}`);
if (problems.length) {
  console.error('Problems:\n  ' + problems.join('\n  '));
  process.exit(1);
}
